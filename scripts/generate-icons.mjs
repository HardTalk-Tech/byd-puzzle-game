#!/usr/bin/env node
// Builds the brand assets from the supplied logo public/brand/byd-logo-white.png
// (white on transparent):
//   public/brand/byd-logo.svg       logo used by the app (the PNG, trimmed, inside an SVG)
//   public/icons/icon-192.png       PWA icons: white logo on black with a gold line
//   public/icons/icon-512.png
//   public/icons/icon-512-maskable.png  (logo kept inside the maskable safe zone)
//   app/icon.svg                    browser tab icon
// Usage: npm run icons   (re-run after replacing byd-logo-white.png)

import { mkdirSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const SOURCE = "public/brand/byd-logo-white.png";

const GOLD = `<linearGradient id="g" x1="0" y1="0" x2="1" y2="0">
  <stop offset="0" stop-color="#9C7A2E"/><stop offset=".3" stop-color="#C9A24A"/>
  <stop offset=".5" stop-color="#F3DC9A"/><stop offset=".7" stop-color="#C9A24A"/>
  <stop offset="1" stop-color="#9C7A2E"/></linearGradient>`;

// Trim the transparent border so the logo sizes exactly to its artwork.
const { data: logoPng, info } = await sharp(SOURCE).trim().png().toBuffer({ resolveWithObject: true });
const logoW = info.width;
const logoH = info.height;
const logoHref = `data:image/png;base64,${logoPng.toString("base64")}`;

// 1. The app logo: same file name as before, so nothing else changes.
writeFileSync(
  "public/brand/byd-logo.svg",
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${logoW} ${logoH}" width="${logoW}" height="${logoH}">
  <!-- Generated by scripts/generate-icons.mjs from ${SOURCE}. -->
  <image href="${logoHref}" width="${logoW}" height="${logoH}"/>
</svg>
`,
);

/** Square icon: black background, logo at `widthRatio` of the size, gold line below. */
function iconSvg(widthRatio, { rounded = false } = {}) {
  const size = 512;
  const w = size * widthRatio;
  const h = (w * logoH) / logoW;
  const x = (size - w) / 2;
  const y = (size - h) / 2 - h * 0.25;
  const lineW = w * 0.62;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">
  <defs>${GOLD}</defs>
  <rect width="${size}" height="${size}" ${rounded ? 'rx="96"' : ""} fill="#0A0A0B"/>
  <image href="${logoHref}" x="${x}" y="${y}" width="${w}" height="${h}"/>
  <rect x="${(size - lineW) / 2}" y="${y + h * 1.45}" width="${lineW}" height="${Math.max(4, h * 0.09)}" rx="3" fill="url(#g)"/>
</svg>`;
}

mkdirSync("public/icons", { recursive: true });
const regular = Buffer.from(iconSvg(0.76));
// Maskable icons may be cropped to a circle of 80% diameter: keep the logo well inside.
const maskable = Buffer.from(iconSvg(0.56));

await sharp(regular).resize(192, 192).png().toFile("public/icons/icon-192.png");
await sharp(regular).resize(512, 512).png().toFile("public/icons/icon-512.png");
await sharp(maskable).resize(512, 512).png().toFile("public/icons/icon-512-maskable.png");
writeFileSync("app/icon.svg", iconSvg(0.84, { rounded: true }));

console.log(`Logo ${logoW}×${logoH} → public/brand/byd-logo.svg, public/icons/*.png, app/icon.svg`);
